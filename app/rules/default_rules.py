def get_default_rules() -> list[DetectionRule]:
    """Returns fresh DetectionRule instances (avoids shared mutable state)."""
    return [
        DetectionRule(
            rule_id=r.rule_id,
            name=r.name,
            category=r.category,
            description=r.description,
            pattern=r.pattern,
            severity=r.severity,
            confidence=r.confidence,
            enabled=r.enabled,
            tags=r.tags,
            recommendation=r.recommendation,
            is_builtin=True,
        )
        for r in DEFAULT_RULES
    ]
